#!/usr/bin/env python3
"""Render the agent view of the corpus decision cards.

For every `knowledge/operator/<op>/corpus/decisions.yaml` (and `knowledge/general/corpus/decisions.yaml`) write a
compact `cards.md` next to the operator README: one short block per card with the fields an optimizing agent acts
on (when it applies, what to try, what was reported, limits) and none of the extraction bookkeeping (source ids,
upstream-review boilerplate, provenance). The YAML stays the single source of truth; edit it, then re-run:

    python3 tools/agent/build_cards.py          # rewrite all cards.md
    python3 tools/agent/build_cards.py --check  # exit 1 if any cards.md is stale
"""
import argparse
import os
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[2]
KN = ROOT / "knowledge"
EVIDENCE = {"reported_experience": "reported", "source_observed": "source-only"}
TYPE = {"performance_candidate": "performance", "constraint": "constraint", "semantic": "semantics"}
ALL_LANGS = {"triton", "gluon", "flydsl", "hip", "ck", "asm", "tilelang"}  # every language the corpus extracts
OUTCOME = {"beneficial": "gain reported", "mixed": "mixed", "constraint": "constraint", "not_reported": "no result"}
HEADER = """# {title} — decision cards

Generated by `tools/agent/build_cards.py` from `corpus/decisions.yaml` (maintained on `main`); edit the YAML, not this file.

How to read a card:
- **Evidence** — `reported`: an upstream PR or benchmark reported an outcome (not reproduced here; the outcome
  line says what was reported). `source-only`: observed in shipped source or configs; it shows what an
  implementation does, not that it wins. Treat both as hypotheses and measure on your own kernel and shapes.
- **Applies** — the languages/dtypes/GPUs the card was derived from. For a kernel in another language the card is a
  porting idea, not a recipe.
- `constraint` cards are correctness or validity rules: check them before trusting a speedup.
"""


def load(p):
    return yaml.safe_load(p.read_text()) or {}


def cards_path(owner):
    return KN / "general/cards.md" if owner == "general" else KN / "operator" / owner / "cards.md"


def rel(target, frm):
    return os.path.relpath(target, frm.parent)


def langs(ls):
    return "all" if not ls or ALL_LANGS <= set(ls) else "/".join(ls)


def applies(c):
    m = c.get("match") or {}
    parts = []
    for k, label in (("target_languages", "lang"), ("dtypes", "dtype"), ("gfx", "gfx"), ("exclude_gfx", "not gfx"),
                     ("regimes", "regime")):
        if m.get(k):
            parts.append(f"{label} {langs(m[k]) if k == 'target_languages' else '/'.join(map(str, m[k]))}")
    if m.get("shape"):
        parts.append("shape " + ", ".join(f"{k}={v}" for k, v in m["shape"].items()))
    for r in m.get("requires") or []:
        parts.append(f"requires `{r}`")
    return "; ".join(parts) or "any"


def link_refs(refs, out):
    links = []
    for r in refs or []:
        path, _, lines = str(r).partition(":")
        p = ROOT / path
        if p.exists():
            links.append(f"[{Path(path).name}{':' + lines if lines else ''}]({rel(p, out)}{'#L' + lines.split('-')[0] if lines and p.suffix != '.md' else ''})")
    return links


def card_block(c, out):
    lines = [f'<a id="{c["id"]}"></a>', f"### {c['question']}", ""]
    ev = EVIDENCE.get(c.get("evidence_level"), c.get("evidence_level"))
    lines.append(f"`{c['id']}` · {TYPE.get(c.get('type'), c.get('type'))} · evidence: **{ev}** · applies: {applies(c)}")
    lines.append("")
    if c.get("conditions"):
        lines.append("**When:** " + "; ".join(c["conditions"]))
    if c.get("actions"):
        lines.append("**Try:**")
        lines += [f"- {a}" for a in c["actions"]]
    for key, label in (("why", "Why"), ("alternatives", "Alternatives"), ("limitations", "Limits")):
        v = c.get(key)
        if v:
            lines.append(f"**{label}:** " + " ".join(v) if len(v) == 1 else f"**{label}:**")
            if len(v) > 1:
                lines += [f"- {x}" for x in v]
    exp = [e for e in c.get("experience") or [] if e.get("summary")]
    if exp:
        lines.append("**Reported:**")
        lines += [f"- {OUTCOME.get(e.get('outcome'), e.get('outcome'))}: {e['summary']}" for e in exp]
    sols = c.get("solutions") or []
    if sols:
        lines.append("**Existing implementations:** " + "; ".join(f"{s.get('backend')}: {s.get('mechanism')}" for s in sols))
    refs = link_refs(c.get("references"), out)
    if refs:
        lines.append("**Read more:** " + ", ".join(refs))
    return "\n".join(lines) + "\n"


def render(owner, title, data, index):
    out = cards_path(owner)
    cards = sorted(data.get("cards") or [], key=lambda c: (c.get("evidence_level") != "reported_experience",
                                                             c.get("type") != "constraint", c["id"]))
    body = [HEADER.format(title=title)]
    if data.get("traits"):
        body.append("Design traits that some cards require (`requires`):")
        body += [f"- `{k}` — {v}" for k, v in data["traits"].items()]
        body.append("")
    if cards:
        body.append("| card | type | evidence | languages | question |")
        body.append("| --- | --- | --- | --- | --- |")
        for c in cards:
            body.append(f"| [`{c['id']}`](#{c['id']}) | {TYPE.get(c.get('type'), c.get('type'))} | "
                        f"{EVIDENCE.get(c.get('evidence_level'), c.get('evidence_level'))} | "
                        f"{langs((c.get('match') or {}).get('target_languages'))} | {c['question']} |")
        body.append("")
        body += [card_block(c, out) for c in cards]
    shared = [s for s in data.get("shared_cards") or [] if s in index]
    if shared:
        body.append("## Also relevant: cards owned by other operators\n")
        for s in sorted(shared):
            o, q = index[s]
            body.append(f"- [`{s}`]({rel(cards_path(o), out)}#{s}) — {q}")
        body.append("")
    return out, "\n".join(body).rstrip() + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    sources = {"general": KN / "general/corpus/decisions.yaml"}
    sources.update({p.parent.parent.name: p for p in sorted(KN.glob("operator/*/corpus/decisions.yaml"))})
    datas = {o: load(p) for o, p in sources.items()}
    index = {c["id"]: (o, c["question"]) for o, d in datas.items() for c in d.get("cards") or []}
    stale = []
    for o, d in datas.items():
        out, text = render(o, "General methods" if o == "general" else o, d, index)
        if a.check:
            if not out.exists() or out.read_text() != text:
                stale.append(str(out.relative_to(ROOT)))
        else:
            out.write_text(text)
    if a.check and stale:
        print("stale:", *stale, sep="\n  ")
        sys.exit(1)
    print(f"{len(datas)} card files, {len(index)} cards" + (" (check ok)" if a.check else ""))


if __name__ == "__main__":
    main()
