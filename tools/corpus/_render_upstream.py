"""Render PR evidence with its reported scope and independently assessed attribution."""
from __future__ import annotations

from html import escape
import os

import upstream


def safe(value):
    return escape(str(value)).replace("|", "&#124;").replace("\n", " ")


def metric_text(metric):
    unit = metric["unit"]
    if "before" in metric:
        raw = f"{metric['before']:g} → {metric['after']:g} {unit}"
    else:
        raw = f"{metric['value']:g} {unit}"
    normalized = f"; normalized speedup {upstream.speedup(metric):.4g}×"
    if metric["kind"] == "speedup":
        normalized = ""
    return f"{safe(metric['kind'])}: {raw} ({safe(metric['statistic'])}){normalized}"


def grade(label, confidence):
    missing = "; missing: " + ", ".join(safe(x) for x in confidence["missing_evidence"]) if confidence["missing_evidence"] else ""
    return f"**{label}: {confidence['level']}** — " + " ".join(safe(x) for x in confidence["reasons"]).rstrip(".") + missing + "."


def card_section(catalog, card, page):
    review = card["upstream_review"]
    out = ["", "#### Upstream PR effects", "", f"**Review: {review['status']}**."]
    if review["status"] == "unreviewed":
        out += ["PR provenance and reported effects have not been reviewed for this direction; effect confidence is unknown."]
    else:
        out += [safe(review["summary"]) + f" Checked {safe(review['checked_at'])}."]
    for entry in card.get("experience", []):
        if entry["provenance"]["kind"] != "upstream_report":
            continue
        ref = entry["upstream"]
        pr = catalog.upstream[ref["pr"]]
        relative = os.path.relpath(catalog.root / upstream.DIRECTORY / f"{pr['number']}.md", page.parent).replace(os.sep, "/")
        assessment = ref["assessment"]
        target = assessment["applies_to"]
        out += ["", f"- **[PR #{pr['number']}]({upstream.REPOSITORY}/pull/{pr['number']}) · {pr['state']} · {entry['outcome']}** — {safe(entry['summary'])}",
                "  Conditions: " + " ".join(safe(x) for x in entry["conditions"]),
                f"  Direction: {safe(target['backend'])}; " + ", ".join(safe(x) for x in target["axes"]),
                "  " + grade("Association", assessment["association"]),
                "  " + grade("Independent attribution", assessment["attribution"]["confidence"])
                + f"; effect belongs to a **{assessment['attribution']['scope']}** change.",
                "  Verification: **upstream report, not reproduced**. Applicability to a new workload remains unvalidated."]
        changes = {c["id"]: c for c in pr["changes"]}
        for key in ref["change_refs"]:
            change = changes[key]
            out.append(f"  Change: [{change['commit'][:12]}]({upstream.REPOSITORY}/commit/{change['commit']}) — {safe(change['summary'])}")
        results = {r["id"]: r for r in pr["results"]}
        for key in ref["result_refs"]:
            result = results[key]
            context = result["context"]
            out += [f"  [Result: {safe(key)}]({relative}#{key}) — **{context['scope']}**; {safe(result['summary'])}",
                    "  " + grade("Effect confidence", result["confidence"])]
            out += ["  " + metric_text(m) for m in result["metrics"]]
            if not result["metrics"]:
                out.append("  Quantitative effect: **not reported**.")
    return out


def render_record(root, pr):
    page = root / upstream.DIRECTORY / f"{pr['number']}.md"
    url = f"{upstream.REPOSITORY}/pull/{pr['number']}"
    out = [f"# AITER PR #{pr['number']}: {pr['title']}", "",
           "GENERATED by `tools/corpus/build.py`; edit the adjacent YAML inputs instead.", "",
           f"[Upstream PR]({url}) · **{pr['state']}** · [Canonical evidence]({pr['number']}.yaml)", "",
           "These are attributed upstream reports, not reproduced benchmarks. PR base/head revisions are metadata; "
           "only the explicit comparison context identifies measured revisions.", "",
           f"Captured: {pr['captured_at']}; PR updated: {pr['updated_at']}.", "",
           f"PR base: `{pr['base_commit']}`; head: `{pr['head_commit']}`; merge: `{pr['merge_commit'] or 'not merged'}`.", "",
           "## Reviewed changes", ""]
    for change in pr["changes"]:
        out += [f"### {change['id']}", "", safe(change["summary"]), "",
                f"[Source]({upstream.REPOSITORY}/blob/{change['commit']}/{change['file']}) · "
                f"parent `{change['parent_commit']}` → change `{change['commit']}`.", "",
                "Before:", "", "```text", change["before"] or "(file added)", "```", "",
                "After:", "", "```text", change["after"], "```", ""]
    for result in pr["results"]:
        out += [f'<a id="{result["id"]}"></a>', f"## {result['id']}", "",
                f"**Outcome: {result['outcome']}** — {safe(result['summary'])}", "",
                grade("Effect confidence", result["confidence"]), "",
                "| Comparison field | Reported value |", "|---|---|"]
        out += [f"| {key} | {safe(value) if value is not None else '**unknown**'} |" for key, value in result["context"].items()]
        out += [""] + ["- " + metric_text(m) for m in result["metrics"]]
        out += ["  Reported row/claim: " + safe(m["source"]["quote"]) for m in result["metrics"]]
        if not result["metrics"]:
            out += ["Quantitative effect: **not reported**; this does not mean zero gain."]
        out += ["", "Sources: " + ", ".join(f"[{s}](#source-{s})" for s in result["source_refs"]), ""]
        out += ["- " + safe(x) for x in result["limitations"]] + [""]
    out += ["## Captured source excerpts", "",
            "Fingerprints bind the excerpts recorded here; they do not authenticate an author or prove a measurement. "
            "PR text may change after capture. Retain cited excerpts when adding a new revision.", ""]
    for source in pr["sources"]:
        out += [f'<a id="source-{source["id"]}"></a>', f"### {source['id']}", "",
                f"[Original source]({source['url']}) · SHA-256 `{source['sha256']}`", "",
                f"Source updated: {source['updated_at']}; captured: {source['captured_at']}.", ""]
        # Escape raw HTML from upstream text; excerpts are data, not active page content.
        out += [("> " + escape(line)).rstrip() for line in source["excerpt"].splitlines()] + [""]
    return page, "\n".join(out)
