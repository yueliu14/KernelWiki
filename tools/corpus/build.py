#!/usr/bin/env python3
"""Render operator-local corpus pages and the small global index from canonical YAML."""
from __future__ import annotations

import argparse
from collections import Counter
from html import escape
import json
import os
from pathlib import Path

from validate import Catalog, qualified, source_refs


def link(label, target, page, anchor=""):
    relative = os.path.relpath(target, page.parent).replace(os.sep, "/")
    return f"[{label}]({relative}{'#' + anchor if anchor else ''})"


def anchor(ref):
    return ref.replace(":", "-")


def cell(value):
    return escape(str(value)).replace("|", "&#124;").replace("\n", " ")


def code(value):
    return "<code>" + cell(value) + "</code>"


def card_link(catalog, ref, page):
    owner = catalog.card_owners[ref]
    return link(ref, catalog.operators[owner]["path"] / "decisions.md", page, ref)


def source_link(catalog, ref, page):
    owner = catalog.source_owners[ref]
    return link(ref, catalog.operators[owner]["path"] / "source_evidence.md", page, anchor(ref))


def seed_link(catalog, ref, page):
    owner = catalog.seed_owners[ref]
    return link(ref, catalog.operators[owner]["path"] / "seeds.md", page, anchor(ref))


def provenance(catalog, rows):
    return ", ".join(f"`{s}` ({catalog.snapshot(s)['commit'][:12]})" for s in sorted({r['snapshot'] for r in rows}))


def common_header(catalog, op, kind):
    bundle = catalog.operators[op]
    path = bundle["path"] / f"{kind}.md"
    out = [f"# {op} — {'development decisions' if kind == 'decisions' else 'source evidence'}", "",
           "GENERATED by `tools/corpus/build.py`; edit the adjacent YAML inputs instead.", "",
           link("Operator overview", bundle["path"].parent / "README.md", path) + " · " +
           link("Corpus catalog", catalog.root / "corpus/README.md", path) + " · " +
           link("Extraction scope", bundle["path"] / "scope.yaml", path) + " · " +
           link("Axes and dependencies", bundle["path"] / "performance_axes.yaml", path), "",
           "Source observations identify implementation precedents and constraints; they do not establish "
           "a performance winner, runtime engagement or support for every shape and GPU.", ""]
    return path, out


def references_and_limits(catalog, op, page):
    bundle = catalog.operators[op]
    out = ["## Coverage limits", ""]
    out += [f"- {text}" for text in bundle["scope"].get("coverage_notes", [])]
    out += ["", "## Upstream correctness references", "",
            "These are test sources at pinned revisions, not results from executing the tests.", ""]
    for row in bundle["scope"].get("validation_sources", []):
        out.append(f"- [{row['file']}]({catalog.source_url(row)}) (`{row['snapshot']}`).")
    out += ["", "## Sources", "",
            "- " + link("Owned source observations", bundle["path"] / "source_evidence.yaml", page),
            "- " + link("Owned cards and shared-card references", bundle["path"] / "decisions.yaml", page), ""]
    return out


def render_decisions(catalog, op):
    bundle = catalog.operators[op]
    page, out = common_header(catalog, op, "decisions")
    own = bundle["decisions"]["cards"]
    shared = bundle["decisions"].get("shared_cards", [])
    out += [f"{len(own)} owned cards; {len(shared)} shared-card references. "
            "Shared cards retain one canonical body in their owning operator.", "",
            link("Source evidence", bundle["path"] / "source_evidence.md", page), ""]
    if bundle["decisions"].get("traits"):
        out += ["## Design traits", "",
                "A required trait must be established for the actual design before the card applies.", ""]
        out += [f"- `{name}` — {text}" for name, text in bundle["decisions"]["traits"].items()]
        out.append("")
    out += ["## Owned decisions", "", "| card | type | question |", "|---|---|---|"]
    for c in own:
        out.append(f"| [{c['id']}](#{c['id']}) | {c['type']} | {cell(c['question'])} |")
    out.append("")
    for c in own:
        out += [f'<a id="{c["id"]}"></a>', f"### {c['question']}", "",
                f"**Card:** `{c['id']}` · **Type:** `{c['type']}` · **Evidence:** `source_observed`", "",
                "**Axes:** " + ", ".join(f"`{a}`" for a in c["axes"]), "",
                "#### Applicability", ""]
        for field, value in c["match"].items():
            out.append(f"- `{field}`: " + ", ".join(code(x) for x in value) if isinstance(value, list)
                       else f"- `{field}`: {code(json.dumps(value, sort_keys=True))}")
        for field, title in [("conditions", "Use when"), ("actions", "Try"), ("why", "Rationale"),
                             ("alternatives", "Keep as alternatives")]:
            if c.get(field):
                out += ["", f"#### {title}", "", *[f"- {s}" for s in c[field]]]
        if c.get("solutions"):
            out += ["", "#### Other implementations", ""]
            for sol in c["solutions"]:
                out.append(f"- **{sol['backend']}** — {sol['mechanism']} " +
                           ", ".join(source_link(catalog, r, page) for r in sol["source_evidence"]))
        out += ["", "#### Evidence", ""]
        for ref in c["source_evidence"]:
            row = catalog.resolve_source(ref)
            location = f"{row['file']}:{row['line']}" + (f"-{row['end_line']}" if row.get("end_line") else "")
            out.append(f"- {source_link(catalog, ref, page)} — [{location}]({catalog.source_url(row)}).")
        for ref in c.get("shipped_evidence", []):
            out.append(f"- Shipped selection: {seed_link(catalog, ref, page)}; no measurement is inferred.")
        if c.get("references"):
            out += ["", "#### Background", ""]
            for ref in c["references"]:
                path = ref.split(":", 1)[0]
                out.append("- " + link(ref, catalog.repo_path(path), page))
        out += ["", "#### Limits", "", *[f"- {s}" for s in c["limitations"]], ""]
    out += ["## Shared decisions", "",
            "Follow these references for the full conditions, alternatives and source evidence. "
            "A match to this operator does not establish all dtype, shape or design conditions.", "",
            "| card | owner | question |", "|---|---|---|"]
    for ref in shared:
        out.append(f"| {card_link(catalog, ref, page)} | {catalog.card_owners[ref]} | {cell(catalog.cards[ref]['question'])} |")
    if not shared:
        out.append("| — | — | No shared cards declared. |")
    if bundle["axes"].get("dependencies"):
        out += ["", "## Coupled decisions", ""]
        for d in bundle["axes"]["dependencies"]:
            out.append(f"- **{d['id']}**: {d['rule']} " +
                       ", ".join(card_link(catalog, ref, page) for ref in d.get("decision_refs", [])))
    if bundle["tuning"]["records"]:
        out += ["", "## Shipped starting points", "", link("Owned configuration and backend-selection groups", bundle["path"] / "seeds.md", page), ""]
    out += [""] + references_and_limits(catalog, op, page)
    return page, "\n".join(out)


def render_source(catalog, op):
    bundle = catalog.operators[op]
    page, out = common_header(catalog, op, "source_evidence")
    rows = bundle["evidence"]["source_evidence"]
    borrowed = sorted(r for r in catalog.used_sources(op) if catalog.source_owners[r] != op)
    out += [f"{len(rows)} owned observations from {len(bundle['evidence']['coverage'])} scoped files; "
            f"{len(borrowed)} source references are resolved from other operators.", "",
            "**Owned snapshots:** " + provenance(catalog, rows) + ".", "",
            "`symbol_declaration` locates a function and its extent; its ID binds the recorded "
            "excerpt, not every statement in the function. `interface_parameter` is an occurrence "
            "of a named parameter, not a decoded binary implementation.", "",
            "## Coverage by language", "", "| language | observations |", "|---|---:|"]
    out += [f"| {language} | {n} |" for language, n in sorted(Counter(r["language"] for r in rows).items())]
    out += ["", "## Owned files", "", "| snapshot | scope language | file | observations |", "|---|---|---|---:|"]
    for row in bundle["evidence"]["coverage"]:
        out.append(f"| {row['snapshot']} | {row['language']} | [{row['file']}]({catalog.source_url(row)}) | {row['evidence_records']} |")
    out += ["", "The scope language supplies the host/helper backend context. Explicitly decorated "
            "kernels in mixed Python files retain their own language.", "", "## Observations", ""]
    for category in sorted({r["category"] for r in rows}):
        out += [f"### {category}", "", "| reference | language | source | observed construct |", "|---|---|---|---|"]
        for row in rows:
            if row["category"] != category:
                continue
            ref = qualified(row)
            location = f"{row['file']}:{row['line']}"
            out.append(f'| <a id="{anchor(ref)}"></a>{code(ref)} | {row["language"]} | '
                       f'[{location}]({catalog.source_url(row)}) | {code(row["match"])} |')
        out.append("")
    out += ["## Shared source references", "",
            "The evidence stays in its owner; only references are listed here.", "",
            "| reference | owner |", "|---|---|"]
    for ref in borrowed:
        out.append(f"| {source_link(catalog, ref, page)} | {catalog.source_owners[ref]} |")
    if not borrowed:
        out.append("| — | No borrowed source observations. |")
    if bundle["evidence"].get("missing"):
        out += ["", "## Recorded extraction gaps", ""]
        for row in bundle["evidence"]["missing"]:
            out.append(f"- `{row['snapshot']}` / `{row['subtree']}`: {row['why']}")
    out += [""] + references_and_limits(catalog, op, page)
    return page, "\n".join(out)


def render_seeds(catalog, op):
    bundle = catalog.operators[op]
    page = bundle["path"] / "seeds.md"
    out = [f"# {op} — shipped starting points", "",
           "GENERATED by `tools/corpus/build.py`. These are upstream-selected configuration groups "
           "and backend-selection counts, not measured winners. A group can contain several shapes; "
           "its most frequent value is not a performance recommendation.", "",
           link("Development decisions", bundle["path"] / "decisions.md", page) + " · " +
           link("Machine-readable records", bundle["path"] / "tuned_configs.yaml", page), ""]
    for row in bundle["tuning"]["records"]:
        ref = qualified(row)
        out += [f'<a id="{anchor(ref)}"></a>', f"## {ref}", "",
                f"**Kind:** `{row['kind']}` · **GPU:** `{row.get('gfx', '')}` · **Bucket:** `{row.get('m_bucket', '')}`", ""]
        for key in ("tags", "cu_num", "db_kind", "family", "dtype", "shape_configs", "rows", "knobs",
                    "same_across_configs", "varies_by_shape", "selected_backend_rows"):
            if key in row:
                out.append(f"- `{key}`: " + code(json.dumps(row[key], ensure_ascii=False, sort_keys=True)))
        out += ["", "Sources:", ""]
        for file in row["source_files"]:
            out.append(f"- [{file}]({catalog.source_url(dict(snapshot=row['snapshot'], file=file))})")
        out.append("")
    if bundle["tuning"].get("missing"):
        out += ["## Recorded gaps", ""]
        out += [f"- `{r['snapshot']}`: {r['why']}" for r in bundle["tuning"]["missing"]]
    return page, "\n".join(out).rstrip() + "\n"


def render_index(catalog):
    page = catalog.root / "corpus/README.md"
    out = ["# Operator-local corpus", "",
           "Corpus content lives beside each operator's overview, backend notes and learned knowledge:", "",
           "```text", "knowledge/operator/<operator>/corpus/", "  scope.yaml",
           "  source_evidence.yaml", "  decisions.yaml", "  performance_axes.yaml",
           "  source_evidence.md       # generated", "  decisions.md             # generated",
           "  tuned_configs.yaml       # where upstream seeds are available", "  seeds.md                 # generated where applicable", "```", "",
           "This top-level directory holds only the catalog and this generated navigation page. "
           "The shared production and validation tools live under " + link("tools/corpus", catalog.root / "tools/corpus/README.md", page) + ".", "",
           f"**{len(catalog.operators)} operators · {len(catalog.cards)} canonical cards · "
           f"{len(catalog.sources)} snapshot-qualified source observations · {len(catalog.seeds)} shipped groups.** "
           "Shared references are not counted as additional knowledge records.", ""]
    for family in catalog.data["families"]:
        out += [f"## {family['title']}", "", "| operator | owned cards | shared cards | owned observations | reading |", "|---|---:|---:|---:|---|"]
        for op in family["operators"]:
            b = catalog.operators[op]
            out.append(f"| {link(op, b['path'].parent / 'README.md', page)} | {len(b['decisions']['cards'])} | "
                       f"{len(b['decisions'].get('shared_cards', []))} | {len(b['evidence']['source_evidence'])} | "
                       f"{link('Decisions', b['path'] / 'decisions.md', page)} · {link('Evidence', b['path'] / 'source_evidence.md', page)} |")
        out.append("")
    out += ["## Reference contract", "",
            "- Each decision card and each source observation has one owning operator. Other operators use IDs and links; they do not copy the body.",
            "- Source/config references include a snapshot: `aiter_b3ad6c46:src_…` or `aiter_a6bb4993:cfg_…`. Existing content-ID suffixes are preserved; a path move does not change identity.",
            "- The catalog uses schema version 2 and repository-relative paths. This replaces the old family-level file layout.",
            "- Operator membership and source availability do not certify complete backend coverage, runtime engagement or a measured speedup.",
            "- Correctness-test links are pinned sources, not test results. No new GPU performance measurements or disassembly results are included.", "",
            "## Source snapshots", ""]
    for name, snapshot in catalog.snapshots.items():
        out.append(f"- `{name}`: [{snapshot['commit']}]({snapshot['repository'].removesuffix('.git')}/tree/{snapshot['commit']}).")
    out += ["", "## Maintenance", "", "```bash", "python3 tools/corpus/build.py --emit",
            "python3 tools/corpus/build.py --check", "python3 tools/corpus/validate.py",
            "python3 tools/corpus/validate.py --verify-source /path/to/aiter",
            "python3 tools/corpus/extract.py --operator attention_indexer --aiter /path/to/aiter --check",
            "```", "", "Build and validate all operators by default; `--operator` or `--family` limits the selected output/audit. "
            "Extraction reads the declared git objects, including multiple revisions in one operator. "
            "See the tool guide for refreshing evidence and adding operators.", ""]
    return page, "\n".join(out)


def pages(catalog, operators=None, include_index=True):
    result = {}
    for op in list(catalog.operators) if operators is None else operators:
        for path, text in [render_decisions(catalog, op), render_source(catalog, op)]:
            result[path] = text
        if catalog.operators[op]["tuning"]["records"]:
            path, text = render_seeds(catalog, op)
            result[path] = text
    if include_index:
        path, text = render_index(catalog)
        result[path] = text
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--emit", action="store_true")
    mode.add_argument("--check", action="store_true")
    parser.add_argument("--operator")
    parser.add_argument("--family")
    args = parser.parse_args()
    catalog = Catalog().validate()
    selected = catalog.selected(args.operator, args.family)
    rendered = pages(catalog, selected)
    stale = []
    for path, text in rendered.items():
        if args.emit:
            path.write_text(text, encoding="utf-8")
        elif not path.exists() or path.read_text(encoding="utf-8") != text:
            stale.append(str(path.relative_to(catalog.root)))
    if stale:
        parser.exit(1, "STALE: " + ", ".join(stale) + "; run tools/corpus/build.py --emit\n")
    print(f"OK: {len(rendered)} generated pages for {len(selected)} operators")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
